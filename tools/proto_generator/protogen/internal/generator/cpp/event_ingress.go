type eventIngress uint8

const (
	eventIngressNone eventIngress = iota
	eventIngressScene
	eventIngressGate
)

func kafkaIngressEnabled(message *descriptorpb.DescriptorProto) (bool, error) {
	if message == nil {
		return false, fmt.Errorf("Kafka 事件缺少消息描述符")
	}
	value, _, err := prototools.ReadBoolExtension(message.GetOptions().ProtoReflect(), "OptionKafkaIngress", 700001)
	return value, err
}

// 标注只回答是否允许进入，具体入口由文件位置唯一决定。
func classifyEventIngress(protoPath string, message *descriptorpb.DescriptorProto, logicDir, kafkaDir string) (eventIngress, error) {
	enabled, err := kafkaIngressEnabled(message)
	if err != nil || !enabled {
		return eventIngressNone, err
	}
	for _, field := range message.GetField() {
		if field.GetName() == "entity" || strings.HasSuffix(field.GetName(), "_entity") {
			return eventIngressNone, fmt.Errorf("跨进程事件 %s 含实体句柄字段 %s", message.GetName(), field.GetName())
		}
	}
	path := strings.TrimPrefix(filepath.ToSlash(protoPath), "proto/")
	if path == filepath.ToSlash(filepath.Join(kafkaDir, "gate_event.proto")) {
		return eventIngressGate, nil
	}
	if filepath.ToSlash(filepath.Dir(path))+"/" == strings.TrimSuffix(filepath.ToSlash(logicDir), "/")+"/" {
		return eventIngressScene, nil
	}
	return eventIngressNone, fmt.Errorf("文件 %s 不允许标注 Kafka 事件 %s", protoPath, message.GetName())
}

func eventDescriptor(protoPath, messageName string) *descriptorpb.DescriptorProto {
	wanted := filepath.ToSlash(protoPath)
	for _, file := range internal.FdSet.GetFile() {
		name := filepath.ToSlash(file.GetName())
		if name == wanted || strings.HasSuffix(name, "/"+wanted) {
			return findMessageByName(file, messageName)
		}
	}
	return nil
}

func ingressEvents(ingress eventIngress) []*ProtoEventInfo {
	var result []*ProtoEventInfo
	for _, event := range globalProtoEventList {
		if event.Ingress == ingress {
			result = append(result, event)
		}
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Id < result[j].Id })
	return result
}

func writeKafkaCommandEventWhitelistHeader() error {
	var out strings.Builder
	out.WriteString("// Code generated by protogen. DO NOT EDIT.\n#pragma once\n#include <cstdint>\n\n")
	for _, entry := range []struct {
		name    string
		ingress eventIngress
	}{{"IsSceneCommandEvent", eventIngressScene}, {"IsGateCommandEvent", eventIngressGate}} {
		fmt.Fprintf(&out, "constexpr bool %s(uint32_t eventId)\n{\n    switch (eventId) {\n", entry.name)
		for _, event := range ingressEvents(entry.ingress) {
			fmt.Fprintf(&out, "    case %du: // %s\n", event.Id, event.IdName)
		}
		if len(ingressEvents(entry.ingress)) != 0 {
			out.WriteString("        return true;\n")
		}
		out.WriteString("    default: return false;\n    }\n}\n\n")
	}
	return utils2.WriteFileIfChanged(filepath.Join(filepath.Dir(_config.Global.Paths.ServiceHeaderFile), "kafka_command_event_whitelist.h"), []byte(out.String()))
}
