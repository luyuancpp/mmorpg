package persistschema

import (
	"fmt"
	"sort"
	"strings"
)

// RenderCppHeader 生成 C++ 头文件:世代常量,以及往返一致性测试用的冻结类型与未携带字段清单(§4.3)。
// 只含头文件,不需要登记进 CMakeLists / vcxproj。字符串字面量只有类型名与字段名,全是 ASCII。
func RenderCppHeader(gen uint32, s Schema) []byte {
	frozen := sortedKeys(s.Frozen)
	uncarried := make([]string, 0, len(s.Uncarried))
	for _, name := range s.Uncarried {
		uncarried = append(uncarried, name)
	}
	sort.Strings(uncarried)

	var b strings.Builder
	b.WriteString("// 由 proto 生成器(tools/proto_generator/protogen/internal/persistschema)按 proto/persist_schema_gen.txt 生成,不要手改。\n")
	b.WriteString("// 设计:docs/design/mixed-version-persist-field-protection.md §3、§4.3。\n")
	b.WriteString("#pragma once\n\n")
	b.WriteString("#include <array>\n#include <cstdint>\n#include <string_view>\n\n")
	b.WriteString("namespace persist_schema\n{\n")
	b.WriteString("// 本二进制认识的玩家持久 schema 世代。存盘给两张玩家表盖章 max(kPersistSchemaGen, 加载世代)(§3.3)。\n")
	fmt.Fprintf(&b, "inline constexpr uint32_t kPersistSchemaGen = %d;\n\n", gen)
	b.WriteString("// 显式冻结的持久消息类型全名(§3.2 R1)。往返一致性测试不在这些类型的节点上注入未知字段,但继续向下遍历。\n")
	writeCppStringArray(&b, "kFrozenMessageTypes", frozen)
	b.WriteString("\n// 存盘时不原样携带的持久字段 \"<消息全名>.<字段名>\"(§3.2)。往返一致性测试不经由它们注入。\n")
	writeCppStringArray(&b, "kUncarriedFields", uncarried)
	b.WriteString("} // namespace persist_schema\n")
	return []byte(b.String())
}

func writeCppStringArray(b *strings.Builder, name string, values []string) {
	fmt.Fprintf(b, "inline constexpr std::array<std::string_view, %d> %s = {", len(values), name)
	if len(values) == 0 {
		b.WriteString("};\n")
		return
	}
	b.WriteString("\n")
	for _, v := range values {
		fmt.Fprintf(b, "    %q,\n", v)
	}
	b.WriteString("};\n")
}

// RenderGo 生成 Go 侧的世代常量包(go/shared/generated/persistschema)。
func RenderGo(gen uint32) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by protogen from proto/persist_schema_gen.txt. DO NOT EDIT.\n\n")
	b.WriteString("// Package persistschema 提供本二进制认识的玩家持久 schema 世代,\n")
	b.WriteString("// 设计见 docs/design/mixed-version-persist-field-protection.md §3。\n")
	b.WriteString("package persistschema\n\n")
	b.WriteString("// Gen 是本二进制认识的玩家持久 schema 世代。go/db 据此判定超前延后、倒退拒写(§6.2);\n")
	b.WriteString("// 比较时 persist_schema_gen 为 0 的记录按 1 处理(§3.3)。\n")
	fmt.Fprintf(&b, "const Gen uint32 = %d\n", gen)
	return []byte(b.String())
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k, v := range m {
		if v {
			out = append(out, k)
		}
	}
	sort.Strings(out)
	return out
}
